<?php

namespace App\Enums;

enum BuybackState: string
{
    case DRAFT = 'BUYBACK_DRAFT';
    case WAITING_FOR_PL_OFFER = 'BUYBACK_WAITING_FOR_PL_OFFER';
    case PL_OFFERED = 'BUYBACK_PL_OFFERED';
    case WAITING_FOR_FINAL_PRICE = 'BUYBACK_WAITING_FOR_FINAL_PRICE';
    case FINAL_PRICE_APPROVED = 'BUYBACK_FINAL_PRICE_APPROVED';
    case CUSTOMER_OFFER_READY = 'BUYBACK_CUSTOMER_OFFER_READY';
    case OFFER_SENT = 'BUYBACK_OFFER_SENT';
    case CUSTOMER_ACCEPTED = 'BUYBACK_CUSTOMER_ACCEPTED';
    case ITEM_RECEIVED_AK = 'BUYBACK_ITEM_RECEIVED_AK';
    case ITEM_CHECKED_AK = 'BUYBACK_ITEM_CHECKED_AK';
    case RETAINED_AK = 'BUYBACK_RETAINED_AK';
    case READY_TO_PL = 'BUYBACK_READY_TO_PL';
    case SENT_TO_PL = 'BUYBACK_SENT_TO_PL';
    case RECEIVED_PL = 'BUYBACK_RECEIVED_PL';
    case INVOICE_TO_PL_REQUIRED = 'BUYBACK_INVOICE_TO_PL_REQUIRED';
    case WAITING_FOR_PL_PAYMENT = 'BUYBACK_WAITING_FOR_PL_PAYMENT';
    case PAID_BY_PL = 'BUYBACK_PAID_BY_PL';

    public function isTerminal(): bool
    {
        return in_array($this, [self::RETAINED_AK, self::PAID_BY_PL], true);
    }
}
